"""Export reviewable tables from the same JSON consumed by the game reference and drops."""

import argparse
import json
import math
from pathlib import Path


def render(root: Path) -> str:
    content = root / "godot/Content/Loot"
    monsters = json.loads((content / "monsters.json").read_text(encoding="utf-8"))
    bases = [base for base in json.loads((content / "bases.json").read_text(encoding="utf-8")) if base.get("catalog_visible", True)]
    families = json.loads((content / "affixes.json").read_text(encoding="utf-8"))
    statuses = json.loads((root / "godot/Content/Combat/status-effects.json").read_text(encoding="utf-8"))
    status_rules = {entry["kind"].lower(): entry for entry in statuses["effects"]}
    lines = [
        "# Live loot tables", "",
        "Generated by `python tools/export_loot_tables.py` from `godot/Content/Loot/*.json`.",
        "The native Reference browser uses these same files: Monsters, Items and Affixes.", "",
        "## Generation rules", "",
        "- Gold and equipment are independent groups. Gold requires world pickup; equipment grants zero or one item.",
        "- Equipment rarity, slot and base are separate weighted choices. Base weights split the selected slot's probability.",
        "- Each rarity affix slot is occupied independently with probability 55%. Capacities: Common 0, Uncommon 2, Rare 4, Epic 6, Legendary 8.",
        "- Eligible families are weighted without replacement; prefix/suffix labels impose no additional quotas.",
        "- Every affix family uses T1 strongest and T7 weakest. Internal power ranks 1–7 are displayed as T7–T1, preserving values and item-level gates.",
        "- Tier roll: d20 + floor((highest eligible research rank − 1) / 2) + min(5, floor(max(0, Luck) / 5)).",
        "  Research ranks have thresholds 1, 9, 14, 17, 18, 19, 20; clamp to the family's eligible rank interval.",
        "- Quality: min(100, d100 + max(0, Luck)); interpolate within the selected range and round to the family's precision. Dice tiers grant fixed count/sides.",
        "- Gold amount: min + floor((max − min) × (min(100, d100 + max(0, Luck)) − 1) / 99).",
        "- Equipment occurrence/rarity use cumulative probabilities F(L) = F(0) ** (1 + max(0, Luck) / scale), with scale 100 and a single d1000000 selection roll. Thresholds round half upward to that precision.",
        "- Slot, base, family and occupancy weights remain unchanged. Luck does not bypass item-level gates. The live bestiary uses captured player Luck; these base tables use Luck 0.",
        "- Defeat captures outcomes once. Placement, inspection and pickup retries do not reroll them.",
        "- Four prepared leech/critical affix families remain excluded from drops. Independent base critical checks are active; enabling those affix families is a separate decision.",
        "- Prices and research probability exports are not runtime inputs. Base templates supply implicit stats; existing bow damage/cadence/mana and inventory shapes are retained.",
        "- A playable run grants one selected Common bow, sword or wand, once. All three temporarily use the same bow attack. The legacy full kit is only a fixture.", "",
        "## Loot by monster", "",
        "Sentinel is currently the only reward-bearing monster type. Sandbox Sentinel uses the same table. Training targets grant no rewards.", "",
    ]
    for monster in monsters:
        lines += [f"### {monster['name_en']} / {monster['name_uk']}", "",
                  f"ID: `{monster['id']}`. Item level: {monster['item_level']}. Guaranteed gold: {monster['gold']['minimum']}–{monster['gold']['maximum']}.", "",
                  "| Equipment outcome | Per kill | Affix capacity |", "| --- | ---: | ---: |"]
        capacity = {"none": 0, "Common": 0, "Uncommon": 2, "Rare": 4, "Epic": 6, "Legendary": 8}
        total = sum(row["weight"] for row in monster["equipment_outcomes"])
        for row in monster["equipment_outcomes"]:
            lines.append(f"| {row['rarity']} | {100 * row['weight'] / total:g}% | {capacity[row['rarity']]} |")
        lines += ["", "### Luck-adjusted per-kill chances", "",
                  "| Luck | No equipment | Common | Uncommon | Rare | Epic | Legendary | Any equipment |",
                  "| ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |"]
        for luck in (0, 10, 50, 100):
            cumulative = 0
            lower = 0
            chances = []
            resolution = monster["equipment_roll_sides"]
            for row in monster["equipment_outcomes"]:
                cumulative += row["weight"]
                upper = math.floor(resolution * (cumulative / total) ** (1 + luck / monster["equipment_luck_scale"]) + 0.5)
                chances.append(100 * (upper - lower) / resolution)
                lower = upper
            cells = " | ".join(f"{chance:.4f}%" for chance in chances)
            lines.append(f"| {luck} | {cells} | {100 - chances[0]:.4f}% |")
        lines += ["", "| Slot | Conditional on equipment | Per kill, any rarity | Level-eligible bases |", "| --- | ---: | ---: | ---: |"]
        occurrence = 1 - next(row["weight"] for row in monster["equipment_outcomes"] if row["rarity"] == "none") / total
        for row in monster["slots"]:
            count = sum(base.get("loot_enabled", False) and base["slot"] == row["slot"] and base["item_level"] <= monster["item_level"] for base in bases)
            lines.append(f"| {row['slot']} | {row['weight']:g}% | {row['weight'] * occurrence:g}% | {count} |")
        lines.append("")
    lines += ["## Base catalog", "", f"{len(bases)} named bases across five generations and three branches; {sum(base.get("released", False) for base in bases)} are live. Later-generation balance is pending. Compatibility aliases are omitted. Affix level, equip level and display rating are separate concepts.", "",
              "| ID | Name | Branch | Generation | Live | Required level | Attribute requirement | Affix level | Implicit stats | Weapon | Bag cells |", "| --- | --- | --- | ---: | --- | ---: | --- | --- | --- | --- | --- |"]
    for base in bases:
        modifiers = "; ".join(f"{row['type']} {row['value']:g}" for row in base["modifiers"]) or "—"
        weapon = base.get("weapon")
        attack = "; ".join(f"{part['count']}d{part['sides']}+{part['flat']} {part['type']}" for part in weapon["damage"]) + f"; {weapon['attacksPerSecond']:g}/s; mana {weapon['manaCost']:g}" if weapon else "—"
        size = base["inventorySize"]
        lines.append(f"| `{base['id']}` | {base['name']} | {base['branch']} | {base['generation']} | {base['released']} | {base['required_level'] if base['released'] else 'pending'} | {base['required_attribute_value'] if base['released'] else 'pending'} | {base['item_level'] if base['released'] else 'pending'} | {modifiers} | {attack} | {size['width']}×{size['height']} |")
    lines += ["", "## Affix catalog", "", f"{len(families)} families; {sum(len(family['tiers']) for family in families)} tiers. Fractions are coefficients (0.1 = 10%). Flat grouped damage/resistance grants the listed value to each listed damage type.", ""]
    for family in families:
        lines += [f"### {family['name_en']} / {family['name_uk']}", "",
                  f"`{family['id']}` · {family['category']} · weight {family['weight']} · slots: {', '.join(family['slots'])}.", "",
                  "Enabled." if family["enabled"] else "Prepared; excluded from generation until separately enabled.", ""]
        if family.get("types"):
            lines += [f"Damage types: {', '.join(family['types'])}.", ""]
        lines += ["| Tier | Minimum ilvl | Value range | Unit |", "| --- | ---: | --- | --- |"]
        for _, tier in reversed(list(family["tiers"].items())):
            if family["effect"] in status_rules:
                rule = status_rules[family["effect"]]
                count = tier["status_dice"]
                flat = count * rule["flat_damage_per_die"]
                formula = f"{count}d{rule['dice_sides']}" + (f"{flat:+g}" if flat else "")
                value = f"{100 * tier['minimum']:g}%; {formula}; {rule['duration_seconds']:g}s, every {rule['tick_interval_seconds']:g}s"
            else:
                value = f"{tier['minimum']}d{tier['maximum']}" if family["effect"] == "dice" else f"{tier['minimum']:g}–{tier['maximum']:g}"
            lines.append(f"| {tier['tier_id']} | {tier['min_ilvl']} | {value} | {family['unit']} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the checked-in reference differs from live JSON.")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    destination = root / "docs/loot-tables.md"
    expected = render(root)
    if args.check:
        if not destination.exists() or destination.read_text(encoding="utf-8") != expected:
            raise SystemExit("Loot tables are stale; run python tools/export_loot_tables.py")
        print("Loot tables match live content.")
    else:
        destination.write_text(expected, encoding="utf-8")
        print("Updated docs/loot-tables.md")


if __name__ == "__main__":
    main()
